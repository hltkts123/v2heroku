#!/bin/bash

echo "????????????????????????????????????????????????????????????????"
echo "?          BUILD PowerPoint Cleaner to EXE                     ?"
echo "????????????????????????????????????????????????????????????????"
echo ""

echo "[1/4] Checking Python..."
if ! command -v python3 &> /dev/null; then
    echo "? Python not found! Please install Python 3.6+"
    exit 1
fi
echo "? Python found"

echo ""
echo "[2/4] Installing PyInstaller..."
pip3 install pyinstaller pillow &> /dev/null
if [ $? -ne 0 ]; then
    echo "? Failed to install PyInstaller"
    exit 1
fi
echo "? PyInstaller installed"

echo ""
echo "[3/4] Creating icon..."
python3 create_icon.py 2>/dev/null || echo "! Warning: Failed to create icon, using default"

echo ""
echo "[4/4] Building executable..."
echo ""
echo "Building single file version..."
pyinstaller --noconfirm --clean \
    --name "PowerPointCleaner" \
    --onefile \
    --windowed \
    --icon="icon.ico" \
    --add-data "icon.ico:." \
    ppt_cleaner.py

echo ""
echo "Building batch version..."
pyinstaller --noconfirm --clean \
    --name "PowerPointCleanerBatch" \
    --onefile \
    --windowed \
    --icon="icon.ico" \
    --add-data "icon.ico:." \
    ppt_cleaner_batch.py

echo ""
echo "????????????????????????????????????????????????????????????????"
echo "?                    BUILD COMPLETED                           ?"
echo "????????????????????????????????????????????????????????????????"
echo ""
echo "Executable files created in 'dist' folder:"
echo "  - PowerPointCleaner (single file mode)"
echo "  - PowerPointCleanerBatch (batch mode)"
echo ""
echo "You can distribute these files without Python!"
echo ""
